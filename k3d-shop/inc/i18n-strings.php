/** الترجمة الفعلية - بترجع النص الأصلي زي ما هو لو مفيش ترجمة للغة الحالية أو اللغة هي المصدر أصلاً. */
function k3d_translate( string $text ): string {
	if ( 'ar' === k3d_current_lang() ) {
		return $text;
	}

	$dict = k3d_i18n_dictionary();

	return $dict[ $text ][ k3d_current_lang() ] ?? $text;
}
